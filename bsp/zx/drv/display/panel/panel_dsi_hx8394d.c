#include "panel_com.h"
#include "panel_dsi.h"

#define PANEL_DEV_NAME      "dsi_panel_hx8394d"

#define RESET_PIN "PA.10"

static struct gpio_desc reset;

static int panel_prepare(void)
{
    panel_get_gpio(&reset, RESET_PIN);

    panel_gpio_set_value(&reset, 1);
    aic_delay_ms(5);
    panel_gpio_set_value(&reset, 0);
    aic_delay_ms(5);
    panel_gpio_set_value(&reset, 1);
    aic_delay_ms(5);

    return 0;
}

static int panel_enable(struct aic_panel *panel)
{
    int ret;

    panel_di_enable(panel, 0);
    panel_dsi_send_perpare(panel);

    panel_dsi_dcs_send_seq(panel, 0xB9, 0xFF, 0x83, 0x94);
    panel_dsi_dcs_send_seq(panel, 0xBA, 0x72, 0x83);
    panel_dsi_dcs_send_seq(panel, 0xB1, 0x6C, 0x15,0x15,0x24,0xE4,0x11,0xF1,0x80,0xE4,0x97,0x23,0x80,0xC0,0xD2,0x58);
    panel_dsi_dcs_send_seq(panel, 0xB2, 0x00, 0x64,0x10,0x07,0x22,0x1C,0x08,0x08,0x1C,0x4D,0x00);
    panel_dsi_dcs_send_seq(panel, 0xB4, 0x00, 0xFF,0x03,0x5A,0x03,0x5A,0x03,0x5A,0x01,0x6A,0x30,0x6A);
    panel_dsi_dcs_send_seq(panel, 0xBC, 0x07);
    panel_dsi_dcs_send_seq(panel, 0xBF, 0x41, 0x0E, 0x01);
    panel_dsi_dcs_send_seq(panel, 0xD3, 0x00, 0x06,0x00,0x40,0x07,0x08,0x00,0x32,0x10,0x07,0x00,0x07,0x54,0x15,0x0F,0x05,0x04,0x02,0x12,0x10,0x05,0x07,0x33,0x33,0x0B,0x0B,0x37,0x10,0x07,0x07);
    panel_dsi_dcs_send_seq(panel, 0xD5, 0x04, 0x05,0x06,0x07,0x00,0x01,0x02,0x03,0x20,0x21,0x22,0x23,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x19,0x19,0x18,0x18,0x18,0x18,0x1B,0x1B,0x1A,0x1A,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18);
    panel_dsi_dcs_send_seq(panel, 0xD6, 0x03, 0x02,0x01,0x00,0x07,0x06,0x05,0x04,0x23,0x22,0x21,0x20,0x18,0x18,0x18,0x18,0x18,0x18,0x58,0x58,0x18,0x18,0x19,0x19,0x18,0x18,0x1B,0x1B,0x1A,0x1A,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18);
    panel_dsi_dcs_send_seq(panel, 0xCC, 0x01);
    panel_dsi_dcs_send_seq(panel, 0xB6, 0x51, 0x51);
    panel_dsi_dcs_send_seq(panel, 0xE0, 0x00, 0x10,0x16,0x2D,0x33,0x3F,0x23,0x3E,0x07,0x0B,0x0D,0x17,0x0E,0x12,0x14,0x12,0x13,0x06,0x11,0x13,0x18,0x00,0x0F,0x16,0x2E,0x33,0x3F,0x23,0x3D,0x07,0x0B,0x0D,0x18,0x0F,0x12,0x14,0x12,0x14,0x07,0x11,0x12,0x17);
    panel_dsi_dcs_send_seq(panel, 0xC0, 0x30, 0x14);
    panel_dsi_dcs_send_seq(panel, 0xC7, 0x00, 0xC0, 0x40, 0xC0);
    panel_dsi_dcs_send_seq(panel, 0xDF, 0x87);
    panel_dsi_dcs_send_seq(panel, 0xD2, 0x66);
    panel_dsi_dcs_send_seq(panel, 0x36, (0x1 << 1)); /* Flip Horizontal */

    ret = panel_dsi_dcs_exit_sleep_mode(panel);
    if (ret < 0) {
        pr_err("Failed to exit sleep mode: %d\n", ret);
        return ret;
    }
    aic_delay_ms(120);

    ret = panel_dsi_dcs_set_display_on(panel);
    if (ret < 0) {
        pr_err("Failed to set display on: %d\n", ret);
        return ret;
    }
    aic_delay_ms(40);

    panel_dsi_setup_realmode(panel);
    panel_de_timing_enable(panel, 0);
    panel_backlight_enable(panel, 0);

    return 0;
}

static struct aic_panel_funcs panel_funcs = {
    .disable = panel_default_disable,
    .unprepare = panel_default_unprepare,
    .prepare = panel_prepare,
    .enable = panel_enable,
    .register_callback = panel_register_callback,
};

